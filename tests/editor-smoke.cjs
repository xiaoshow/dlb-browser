const { app, BrowserWindow, ipcMain } = require('electron')
const assert = require('node:assert/strict')
const { mkdtempSync, writeFileSync, readFileSync, rmSync, mkdirSync } = require('node:fs')
const { tmpdir } = require('node:os')
const { join } = require('node:path')
const root = mkdtempSync(join(tmpdir(), 'orbit-editor-'))
app.setPath('userData', root)
const state = { profiles: [{ id: 'demo', name: '指纹功能验证', color: '#4269d8', pinned: true, proxyId: 'direct', timezone: 'Asia/Tokyo', startUrl: 'https://example.com', userAgentMode: 'real', groupId: 'default' }], groups: [{ id: 'default', name: '工作空间', color: '#4269d8' }], proxies: [{ id: 'direct', name: '测试网络', kind: 'direct' }], preloadOnStart: false }
const keys = [...readFileSync(join(__dirname, '../electron/preload.cjs'), 'utf8').matchAll(/^  (\w+):/gm)].map(m => m[1])
let saved
ipcMain.on('test:save', (_event, state) => { saved = state })
const mock = keys.map(key => `${key}: ${key === 'getRunningProfiles' ? 'async () => []' : key === 'loadState' ? `async () => (${JSON.stringify(state)})` : key === 'saveState' ? `(state) => { ipcRenderer.send('test:save', state); return Promise.resolve() }` : key.startsWith('on') ? '() => () => {}' : 'async () => ({ok:true})'}`).join(',')
const preload = join(root, 'preload.cjs')
writeFileSync(preload, `const {contextBridge,ipcRenderer}=require('electron');contextBridge.exposeInMainWorld('profileBrowser',{${mock}})`)
const timer = setTimeout(() => app.exit(1), 20000)
app.whenReady().then(async () => {
  if (process.platform === 'darwin') app.setActivationPolicy('accessory')
  const win = new BrowserWindow({ width: 1240, height: 960, show: false, webPreferences: { preload, sandbox: true } })
  await win.loadFile(join(__dirname, '../dist/index.html'))
  await new Promise(resolve => setTimeout(resolve, 300))
  await win.webContents.executeJavaScript(`document.querySelector('[title="设置 指纹功能验证"]').click()`)
  await new Promise(resolve => setTimeout(resolve, 50))
  const labels = await win.webContents.executeJavaScript(`Array.from(document.querySelectorAll('.fingerprint-settings .field > span')).map(e=>e.textContent)`)
  assert.ok(labels.length >= 20)
  await win.webContents.executeJavaScript(`[...document.querySelectorAll('button')].find(b=>b.textContent==='严格限制预设（影响网站功能）').click(); document.querySelector('.fingerprint-settings').scrollIntoView()`)
  await new Promise(resolve => setTimeout(resolve, 100))
  const screenshotDir = join(__dirname, '../release/previews'); mkdirSync(screenshotDir, { recursive: true })
  writeFileSync(join(screenshotDir, 'fingerprint-editor.png'), (await win.webContents.capturePage()).toPNG())
  const selected = await win.webContents.executeJavaScript(`Array.from(document.querySelectorAll('.fingerprint-settings select')).map(e=>e.value)`)
  assert.ok(selected.includes('noise')); assert.ok(selected.includes('blocked'))
  await win.webContents.executeJavaScript(`[...document.querySelectorAll('button')].find(b=>b.textContent==='恢复浏览功能').click()`)
  await new Promise(resolve => setTimeout(resolve, 50))
  await win.webContents.executeJavaScript(`[...document.querySelectorAll('.environment-editor footer button')].find(b=>b.textContent==='保存').click()`)
  await new Promise(resolve => setTimeout(resolve, 50))
  assert.equal(saved.profiles[0].fingerprint.canvas, 'noise')
  assert.ok(saved.profiles[0].fingerprint.seed)
  assert.equal(saved.profiles[0].fingerprint.mediaDevices, 'real')
  assert.equal(saved.profiles[0].fingerprint.webGPU, 'real')
  assert.equal(saved.profiles[0].fingerprint.webRTC, 'real')
  console.log(`PASS: editor fields, privacy preset and save; preview: ${join(screenshotDir, 'fingerprint-editor.png')}`)
  win.destroy(); clearTimeout(timer); app.exit(0)
}).catch(e => { console.error(e); app.exit(1) })
app.on('quit', () => rmSync(root, { recursive: true, force: true }))
