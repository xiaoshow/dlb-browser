const { app, BrowserWindow } = require('electron')
const assert = require('node:assert/strict')
const { mkdtempSync, mkdirSync, writeFileSync, rmSync } = require('node:fs')
const { tmpdir } = require('node:os')
const { join } = require('node:path')
const { pathToFileURL } = require('node:url')
const root = mkdtempSync(join(tmpdir(), 'orbit-presentation-'))
app.setPath('userData', root)
process.env.ORBIT_DISABLE_REMOTE = '1'
process.env.ORBIT_BACKGROUND_TEST = '1'
process.env.PRISM_EMBEDDED_WINDOWS_TEST = '1'
const server = require('node:http').createServer((_req, res) => { res.setHeader('Content-Type', 'text/html'); res.end('<title>Local profile test</title><h1>Profile test</h1>') })
const timeout = setTimeout(() => { console.error('Presentation test timed out'); app.exit(1) }, 45000)
const pause = () => new Promise(resolve => setTimeout(resolve, 40))
async function waitFor(fn) { for (let n = 0; n < 200; n++) { const value = await fn(); if (value) return value; await pause() } throw new Error('Condition timed out') }
;(async () => {
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
  const local = `http://127.0.0.1:${server.address().port}`
  const profiles = ['alpha', 'beta'].map(id => ({ id, name: id, color: '#4269d8', proxyId: 'direct', timezone: 'Asia/Tokyo', locale: 'ja-JP', startUrl: local, userAgentMode: 'real', groupId: 'default', fingerprint: { seed: id, deviceMemory: 4, canvas: 'noise', webGL: 'noise', audio: 'noise' } }))
  const state = { presentationMode: 'tabs', profiles, proxies: [{ id: 'direct', kind: 'direct', name: '本机直连' }], groups: [{ id: 'default', name: '测试分组', color: '#4269d8' }], preloadOnStart: false, maxRunningProfiles: 1 }
  writeFileSync(join(root, 'workspace.json'), JSON.stringify(state))
  await app.whenReady()
  if (process.platform === 'darwin') app.setActivationPolicy('accessory')
  await import(pathToFileURL(join(__dirname, '../dist-electron/main.js')))
  await app.whenReady()
  const manager = await waitFor(() => BrowserWindow.getAllWindows().find(w => w.webContents.getURL().endsWith('/dist/index.html') && !w.webContents.isLoading()))
  manager.webContents.on('console-message', details => { if (details.level === 'error') console.error(details.message) })
  const api = (method, ...args) => manager.webContents.executeJavaScript(`window.profileBrowser.${method}(...${JSON.stringify(args)})`)
  await waitFor(async () => await manager.webContents.executeJavaScript(`!!document.querySelector('[aria-label="浏览模式"]')`))
  assert.equal((await api('loadState')).profiles.length, 2)
  assert.equal((await api('openProfile', profiles[0], state.proxies[0])).ok, true)
  const view = manager.contentView.children.find(v => v.webContents && v.webContents !== manager.webContents)
  assert.ok(view)
  await waitFor(() => !view.webContents.isLoading())
  const originalContents = view.webContents
  const contentsId = originalContents.id
  const signature = contents => contents.executeJavaScript(`(() => {const c=document.createElement('canvas');c.width=32;c.height=32;const ctx=c.getContext('2d');ctx.fillStyle='rgb(100,120,140)';ctx.fillRect(0,0,32,32);return c.toDataURL()})()`)
  const firstSignature = await signature(view.webContents)
  await view.webContents.executeJavaScript(`window.sessionMarker = 'unchanged'; document.cookie='account=alpha'; localStorage.setItem('account','alpha')`)
  async function selectMode(mode) {
    await manager.webContents.executeJavaScript(`(() => { const select=document.querySelector('[aria-label="浏览模式"]');select.value=${JSON.stringify(mode)};select.dispatchEvent(new Event('change',{bubbles:true})) })()`)
    await waitFor(async () => (await api('loadState')).presentationMode === mode)
  }
  await selectMode('windows')
  const first = await waitFor(() => BrowserWindow.getAllWindows().find(w => w !== manager))
  assert.ok(first.contentView.children.includes(view))
  assert.equal(view.webContents.id, contentsId)
  assert.equal(await view.webContents.executeJavaScript('window.sessionMarker'), 'unchanged')
  await api('openProfile', profiles[0], state.proxies[0])
  assert.equal(BrowserWindow.getAllWindows().length, 2, 'duplicate launch focuses existing window')
  assert.equal((await api('openProfile', profiles[1], state.proxies[0])).ok, true)
  const second = await waitFor(() => BrowserWindow.getAllWindows().find(w => w !== manager && w !== first))
  const secondView = second.contentView.children.find(v => v.webContents && v.webContents !== second.webContents)
  await waitFor(() => !secondView.webContents.isLoading())
  assert.equal(await secondView.webContents.executeJavaScript('localStorage.getItem("account")'), null)
  assert.equal(await secondView.webContents.executeJavaScript('document.cookie'), '')
  assert.equal(await secondView.webContents.executeJavaScript('navigator.deviceMemory'), 4)
  assert.notEqual(await signature(secondView.webContents), firstSignature, 'different Profiles must have different stable Canvas results')
  assert.equal(await signature(view.webContents), firstSignature)
  assert.ok(BrowserWindow.getAllWindows().every(w => !w.isVisible()), 'all test windows must remain hidden')
  assert.deepEqual((await api('getRunningProfiles')).sort(), ['alpha', 'beta'], 'visible profile windows must not be LRU evicted')
  await waitFor(async () => !!await manager.webContents.executeJavaScript('document.querySelector(".profile-manager")'))
  mkdirSync(join(__dirname, '../release/previews'), { recursive: true })
  writeFileSync(join(__dirname, '../release/previews/profile-manager.png'), (await manager.webContents.capturePage()).toPNG())
  await api('saveState', { ...state, presentationMode: 'windows', maxRunningProfiles: 8 })
  await manager.loadFile(join(__dirname, '../dist/index.html'))
  await waitFor(async () => await manager.webContents.executeJavaScript(`document.querySelector('[aria-label="浏览模式"]')?.value === 'windows'`))
  await selectMode('tabs')
  assert.equal(BrowserWindow.getAllWindows().length, 1)
  assert.ok(manager.contentView.children.includes(view))
  assert.equal(view.webContents.id, contentsId)
  assert.equal(await view.webContents.executeJavaScript('window.sessionMarker'), 'unchanged')
  // Return to windows, close one with the native close button, and confirm state is updated.
  await selectMode('windows')
  const alpha = BrowserWindow.getAllWindows().find(w => w.contentView.children.includes(view))
  alpha.close()
  await waitFor(async () => !(await api('getRunningProfiles')).includes('alpha'))
  assert.equal(originalContents.isDestroyed(), true)
  // A closed window's cookies persist when the same profile is opened again.
  await api('openProfile', profiles[0], state.proxies[0])
  const reopened = await waitFor(() => BrowserWindow.getAllWindows().find(w => w.getTitle() === 'alpha — Prism 指纹浏览器'))
  const reopenedView = reopened.contentView.children.find(v => v.webContents && v.webContents !== reopened.webContents)
  await waitFor(() => !reopenedView.webContents.isLoading())
  assert.equal(await reopenedView.webContents.executeJavaScript('localStorage.getItem("account")'), 'alpha')
  assert.equal(await signature(reopenedView.webContents), firstSignature, 'reopening must reuse the exact same fingerprint')
  assert.equal(await reopenedView.webContents.executeJavaScript('typeof window.profileWindow'), 'undefined')
  assert.equal(await reopenedView.webContents.executeJavaScript('typeof window.profileBrowser'), 'undefined')
  manager.close()
  assert.equal(manager.isDestroyed(), false)
  assert.equal(manager.isVisible(), false)
  await waitFor(() => !reopened.webContents.isLoading())
  await reopened.webContents.executeJavaScript("window.profileWindow.action('manager')")
  assert.equal(manager.isVisible(), false, 'background tests must not show or focus windows')
  await waitFor(() => { try { return JSON.parse(require('node:fs').readFileSync(join(root, 'workspace.json'), 'utf8')).presentationMode === 'windows' } catch { return false } })
  assert.equal((await api('loadState')).presentationMode, 'windows')
  console.log('PASS: tab/window modes, view transfer without reload, duplicate launch, independent storage, window LRU protection, native close/reopen and mode persistence')
  clearTimeout(timeout)
  await api('closeProfile', 'alpha'); await api('closeProfile', 'beta')
  await new Promise(resolve => server.close(resolve))
  app.quit()
})().catch(error => { console.error(error); app.exit(1) })
app.on('quit', () => rmSync(root, { recursive: true, force: true }))
